#!/bin/zsh
# THIRD-PARTY-NOTICES.md: the licences of the Go modules linked into the shipped binaries (minigw, minigw-tui,
# minigw-core for every shipped OS/arch), taken from the module cache, plus the Go standard library and the MXC
# sandbox that the MSI carries.
#   third-party-notices.sh            rewrite THIRD-PARTY-NOTICES.md
#   third-party-notices.sh --check    fail when the committed file differs (a new or changed dependency needs a notice);
#                                     build.sh --release runs it, client/notices_test.go checks the same per module
# A module without a licence file or with a licence this script cannot name stops the run: add it to NOTE below
# after reading its licence. Licences that are not permissive (GPL, LGPL, AGPL, MPL) are reported on stderr.
emulate -L zsh; set -eu
export LC_ALL=C
cd ${0:A:h}/..
OUT=THIRD-PARTY-NOTICES.md
CHECK=0; [[ ${1:-} == --check ]] && CHECK=1

# Modules whose module zip has no licence file: the licence their README states (checked by hand).
typeset -A NOTE
NOTE[github.com/mattn/go-localereader]="MIT (stated in the README of https://github.com/mattn/go-localereader; the module ships no licence file)"

mods=$(cd client; for t in darwin/arm64 windows/amd64 windows/arm64 linux/amd64 linux/arm64; do
  GOOS=${t%/*} GOARCH=${t#*/} CGO_ENABLED=0 go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' . ./cmd/minigw-tui ./cmd/minigw-core
done | grep -v -e '^$' -e '^dev\.trojar/' | sort -u)  # dev.trojar/…: our own code (client/cmd/minigw-tui/quiet)

detect() {  # licence name from the text of file $1
  local t; t=$(tr -s '[:space:]' ' ' < $1)
  case $t in
    *"Apache License"*"Version 2.0"*) print Apache-2.0 ;;
    *"Mozilla Public License"*) print MPL-2.0 ;;
    *"GNU AFFERO"*|*"GNU Affero"*) print AGPL ;;
    *"GNU LESSER"*|*"GNU Lesser"*) print LGPL ;;
    *"GNU GENERAL"*|*"GNU General"*) print GPL ;;
    *"Permission is hereby granted, free of charge"*) print MIT ;;
    *"Redistribution and use in source and binary forms"*"Neither the name"*) print BSD-3-Clause ;;
    *"Redistribution and use in source and binary forms"*) print BSD-2-Clause ;;
    *) print UNKNOWN ;;
  esac
}

goroot=$(cd client; go env GOROOT)
golic=(); for f in $goroot/LICENSE $goroot/../LICENSE; do [[ -f $f ]] && { golic=$f; break } done
[[ -n $golic ]] || { print -u2 "FAIL: Go LICENSE not found next to $goroot"; exit 1 }

gen() {
  print "# Third-party notices"
  print
  print "Mini Gateway is built with the software below. Each module is listed with its version and licence; the licence"
  print "texts follow, as they come with the module. Generated by scripts/third-party-notices.sh from the modules that"
  print "are linked into minigw, minigw-tui and minigw-core (Windows, Linux and macOS builds); do not edit by hand."
  print
  print "| Module | Version | Licence |"
  print "| --- | --- | --- |"
  body=
  section() {  # name version licence-name [files…]: table row on stdout, text appended to $body
    local name=$1 ver=$2 lic=$3; shift 3
    print "| $name | $ver | $lic |"
    body+=$'\n'"## $name $ver ($lic)"$'\n\n'
    if (( $# == 0 )); then body+="The module has no licence file."$'\n'
    else local f; for f in "$@"; do body+="~~~~"$'\n'"$(<$f)"$'\n'"~~~~"$'\n'; done; fi
  }
  section "Go standard library and runtime" "go$(cd client; go env GOVERSION | sed 's/^go//')" BSD-3-Clause $golic
  section "wxc-exec.exe (Microsoft eXecution Container, Windows MSI only)" 1.0.1 MIT scripts/mxc-LICENSE.txt
  print -l -- ${(f)mods} | while read -r name ver dir; do
    files=($dir/(LICENSE|LICENCE|COPYING|PATENTS)*(N.))
    [[ $name == modernc.org/sqlite ]] && files=(${files:#*LICENSE-3RD-PARTY.md})  # lists code that is not linked
    lic=${NOTE[$name]:-}
    if [[ -z $lic ]]; then
      [[ -n $files ]] || { print -u2 "FAIL: $name $ver has no licence file; read its licence and add it to NOTE"; exit 1 }
      lic=$(detect $files[1])
      [[ $lic != UNKNOWN ]] || { print -u2 "FAIL: licence of $name $ver ($files[1]) not recognised; add it to NOTE after reading it"; exit 1 }
    fi
    [[ $lic == (MPL|GPL|LGPL|AGPL)* ]] && print -u2 "NON-PERMISSIVE: $name $ver $lic"
    section $name $ver $lic ${files[@]}
  done
  print -r -- $body
}

if (( CHECK )); then
  [[ $(gen) == "$(<$OUT)" ]] || { print -u2 "FAIL: $OUT is out of date (run scripts/third-party-notices.sh and commit)"; exit 1 }
else
  gen > $OUT.new && mv -f $OUT.new $OUT
fi
print "ok: $OUT"
